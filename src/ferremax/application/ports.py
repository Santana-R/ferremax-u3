from __future__ import annotations
from typing import Protocol

class CotizacionRepository(Protocol):
    def obtener(self, cotizacion_id: str, version: int): ...
    def guardar_nueva_version(self, cotizacion): ...
class PedidoRepository(Protocol):
    def obtener(self, pedido_id: str): ...
    def guardar(self, pedido): ...
class InventarioRepository(Protocol):
    def obtener_para_actualizar(self, sku: str, ubicacion_id: str): ...
    def guardar(self, inventario): ...
    def ubicacion_reserva(self, pedido_id: str) -> str: ...
class UnitOfWork(Protocol):
    cotizaciones: CotizacionRepository
    pedidos: PedidoRepository
    inventarios: InventarioRepository
    def __enter__(self): ...
    def __exit__(self, exc_type, exc, traceback): ...
    def registrar(self, actor_id, accion, agregado_id, antes, despues, motivo, evento): ...
    def commit(self): ...
class DisponibilidadReader(Protocol):
    def consultar_disponibilidad(self, sku: str): ...
class PedidoReader(Protocol):
    def consultar_pedido(self, pedido_id: str): ...
