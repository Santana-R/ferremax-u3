/* Las seis operaciones, mediante la vista de atención y la DB efímera de CI. */
const assert=require('node:assert/strict');
const {chromium}=require(process.env.FERREMAX_PLAYWRIGHT || 'playwright');
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1100}}), errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8000/cliente');
  await page.getByRole('button',{name:'Consultar inventario',exact:true}).click();
  await page.waitForFunction(()=>!document.getElementById('product-select').disabled);
  await page.getByLabel('Código del producto').selectOption('FER-API-DEMO');
  await page.getByRole('button',{name:'Consultar disponibilidad',exact:true}).click();
  await page.getByText('10 unidades disponibles',{exact:true}).waitFor();
  await page.screenshot({path:'reports/ci/atencion-inventario.png',fullPage:true});
  await page.getByRole('button',{name:'Crear pedido',exact:true}).click();
  await page.waitForFunction(()=>!document.getElementById('convert-select').disabled);
  const quotes=(await(await page.request.get('http://127.0.0.1:8000/cliente/cotizaciones')).json()).cotizaciones;
  const quote=quotes.find(q=>q.folio==='COT-RENOVAR-DEMO');assert(quote && quote.estado==='Vigente');
  await page.getByLabel('Folio de cotización',{exact:true}).filter({visible:true}).selectOption(quote.id);
  await page.getByLabel('El cliente acepta los productos, precios y condiciones de esta cotización.').check();
  await page.screenshot({path:'reports/ci/atencion-crear-pedido.png',fullPage:true});
  await page.getByRole('button',{name:'Crear pedido pendiente',exact:true}).click();
  await page.getByRole('heading',{name:'Pedido creado',exact:true}).filter({visible:true}).waitFor();
  const selected=await page.locator('#order-select').inputValue();assert(selected);
  await page.getByLabel('Referencia del pago').fill('PAGO-CLIENTE-CI');
  await page.getByLabel('Sucursal de reserva').selectOption('S1');
  await page.getByRole('button',{name:'Confirmar y reservar productos',exact:true}).click();
  await page.getByText('El pago no está autorizado para confirmar el pedido.',{exact:true}).waitFor();
  let order=await(await page.request.get('http://127.0.0.1:8000/pedidos/'+selected)).json();
  assert.equal(order.estado,'Pendiente');
  await page.getByLabel('¿El pago fue autorizado?').selectOption('true');
  await page.getByRole('button',{name:'Confirmar y reservar productos',exact:true}).click();
  await page.getByRole('heading',{name:'Pedido confirmado',exact:true}).waitFor();
  let stock=await(await page.request.get('http://127.0.0.1:8000/inventario/FER-API-DEMO')).json();
  assert.equal(stock.ubicaciones.find(u=>u.ubicacion_id==='S1').disponible,'8');
  await page.screenshot({path:'reports/ci/atencion-confirmado.png',fullPage:true});
  await page.getByLabel('Motivo de cancelación').fill('El cliente solicita cancelar antes del surtido');
  await page.getByLabel('Confirmo la cancelación y la liberación de los productos reservados.').check();
  await page.getByRole('button',{name:'Cancelar y liberar productos',exact:true}).click();
  await page.getByRole('heading',{name:'Pedido cancelado',exact:true}).waitFor();
  await page.getByRole('button',{name:'Consultar pedido',exact:true}).click();
  await page.getByRole('heading',{name:'Pedido consultado',exact:true}).waitFor();
  assert.match(await page.locator('#order-result').innerText(),/cancelado/);
  assert(!await page.locator('#confirm-form').isVisible());assert(!await page.locator('#cancel-form').isVisible());
  stock=await(await page.request.get('http://127.0.0.1:8000/inventario/FER-API-DEMO')).json();
  assert.equal(stock.ubicaciones.find(u=>u.ubicacion_id==='S1').disponible,'10');
  assert(!(await page.locator('body').innerText()).includes(selected));
  await page.screenshot({path:'reports/ci/atencion-pedido-cancelado.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.screenshot({path:'reports/ci/atencion-movil.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('Atención UI: inventario 10 -> pedido pendiente -> pago rechazado -> confirmado/reserva 8 -> cancelado/liberación 10 -> consulta; móvil y ausencia de UUID visible verificados.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
